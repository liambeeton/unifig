// The whole point of `${ENV_VAR}`: a committed config file that carries a
// passphrase without carrying the passphrase.
func TestValidateAcceptsAPassphraseSuppliedByTheEnvironment(t *testing.T) {
	runValidate(t, `networks:
  - name: Guest
    vlan: 30
wlans:
  - name: Home Guest
    network: Guest
    passphrase: ${GUEST_PASSPHRASE}
`, map[string]string{"GUEST_PASSPHRASE": "correct horse battery"}).mustPass(t)
}

// A passphrase the config leaves out is a passphrase unifig does not manage,
// the same rule as every other omitted field (ADR-0004).
func TestValidateAcceptsAWLANWithNoPassphrase(t *testing.T) {
	runValidate(t, `networks:
  - name: Guest
    vlan: 30
wlans:
  - name: Home Guest
    network: Guest
`, nil).mustPass(t)
}

// The bounds are the Controller's own: it refuses a WPA-PSK passphrase outside
// 8 to 64 characters, so unifig refuses one offline rather than letting an
// apply get halfway and stop.
func TestValidateRejectsAPassphraseTheControllerWouldRefuse(t *testing.T) {
	for _, supplied := range []struct{ what, value, want string }{
		{"too short", "short", "8 characters"},
		{"too long", strings.Repeat("a", 65), "64 characters"},
		// Caught here rather than by the Controller partway through an apply.
		{"not printable ASCII", "pässwörd123", "printable ASCII"},
	} {
		t.Run(supplied.what, func(t *testing.T) {
			runValidate(t, `networks:
  - name: Guest
    vlan: 30
wlans:
  - name: Home Guest
    network: Guest
    passphrase: ${GUEST_PASSPHRASE}
`, map[string]string{"GUEST_PASSPHRASE": supplied.value}).
				mustFailWith(t, "line 7", "wlans[0].passphrase", supplied.want)
		})
	}
}

// A validation message is printed, logged and pasted into bug reports, so the
// one thing it must never contain is the secret it is complaining about.
func TestValidateNeverEchoesAPassphrase(t *testing.T) {
	const secret = "sh0rt"
	for _, supplied := range []struct{ what, body, value string }{
		{"too short", "passphrase: ${GUEST_PASSPHRASE}\n", secret},
		{"too long", "passphrase: ${GUEST_PASSPHRASE}\n", strings.Repeat(secret, 20)},
		// The one that pays for the secretFields list: a pattern failure quotes
		// what it rejected everywhere else in unifig.
		{"not printable ASCII", "passphrase: ${GUEST_PASSPHRASE}\n", "pässwörd" + secret},
		{"the wrong type", "passphrase:\n      - ${GUEST_PASSPHRASE}\n", secret},
	} {
		t.Run(supplied.what, func(t *testing.T) {
			res := runValidate(t, `networks:
  - name: Guest
    vlan: 30
wlans:
  - name: Home Guest
    network: Guest
    `+supplied.body, map[string]string{"GUEST_PASSPHRASE": supplied.value})

			if res.exitCode != 1 {
				t.Fatalf("validate exited %d, want 1\nstderr: %s", res.exitCode, res.stderr)
			}
			if strings.Contains(res.stderr, secret) {
				t.Errorf("validate printed the passphrase it was complaining about:\n%s", res.stderr)
			}
		})
	}
}

func TestValidateCatchesDuplicateNetworkNames(t *testing.T) {
	res := runValidate(t, `networks:
  - name: IoT
    vlan: 20
  - name: IoT
    vlan: 21
`, nil).mustFailWith(t, "line 4", "networks[1].name", `"IoT"`)

	if strings.Count(res.stderr, "already defined") != 1 {
		t.Errorf("a duplicated name should be reported once, got:\n%s", res.stderr)
	}
}

func TestValidateInterpolatesEnvVarsIntoValues(t *testing.T) {
	runValidate(t, `networks:
  - name: ${IOT_NAME}
    subnet: ${IOT_SUBNET}
`, map[string]string{
		"IOT_NAME":   "IoT",
		"IOT_SUBNET": "10.20.0.1/24",
	}).mustPass(t)
}

func TestValidateChecksTheInterpolatedValueNotThePlaceholder(t *testing.T) {
	// Proof that interpolation happened before validation: the complaint is
	// about what the environment supplied, not about the ${...} text.
	runValidate(t, `networks:
  - name: IoT
    subnet: ${IOT_SUBNET}
`, map[string]string{
		"IOT_SUBNET": "10.20.0.999",
	}).mustFailWith(t, "networks[0].subnet", "10.20.0.999")
}

func TestValidateFailsNamingAMissingEnvVar(t *testing.T) {
	runValidate(t, `networks:
  - name: IoT
    subnet: ${IOT_SUBNET}
`, nil).mustFailWith(t, "line 3", "networks[0].subnet", "IOT_SUBNET")
}

func TestValidateNamesEveryMissingEnvVar(t *testing.T) {
	res := runValidate(t, `networks:
  - name: ${IOT_NAME}
    subnet: ${IOT_SUBNET}
`, nil).mustFailWith(t, "IOT_NAME", "IOT_SUBNET")

	if res.exitCode != 1 {
		t.Fatalf("exit code = %d, want 1", res.exitCode)
	}
}

func TestValidateDoesNotInterpolateKeys(t *testing.T) {
	// ${...} in a key position is not a reference, so this fails as an unknown
	// field rather than as a missing variable.
	res := runValidate(t, `networks:
  - name: IoT
    ${SUBNET_KEY}: 10.20.0.1/24
`, nil).mustFailWith(t, "unknown field")

	if strings.Contains(res.stderr, "not set in the environment") {
		t.Errorf("a ${...} key should not be treated as a variable reference, got:\n%s", res.stderr)
	}
}

func TestValidateDoesNotRescanInterpolatedValues(t *testing.T) {
	// A secret that happens to contain ${...} is inserted verbatim; it cannot
	// smuggle in a second reference.
	runValidate(t, `networks:
  - name: ${IOT_NAME}
`, map[string]string{
		"IOT_NAME": "${NOT_A_REFERENCE}",
	}).mustPass(t)
}

func TestValidateExplainsThatInterpolationProducesText(t *testing.T) {
	runValidate(t, `networks:
  - name: IoT
    vlan: ${IOT_VLAN}
`, map[string]string{
		"IOT_VLAN": "20",
	}).mustFailWith(t, "networks[0].vlan", "integer", "${ENV_VAR}")
}

func TestValidateDoesNotBlameInterpolationForAHandWrittenValue(t *testing.T) {
	res := runValidate(t, `networks:
  - name: IoT
    vlan: "20"
`, nil).mustFailWith(t, "networks[0].vlan", "integer")

	if strings.Contains(res.stderr, "${ENV_VAR}") {
		t.Errorf("no variable was interpolated here, so interpolation should not be mentioned, got:\n%s", res.stderr)
	}
}

func TestUnknownVerbPrintsUsage(t *testing.T) {
	res := run(t, "vaidate")

	if res.exitCode != 1 {
		t.Errorf("exit code = %d, want 1", res.exitCode)
	}
	if !strings.Contains(res.stderr, "validate") {
		t.Errorf("usage should list the validate command, got: %s", res.stderr)
	}
}

func TestValidateWithTooManyArgumentsPrintsUsage(t *testing.T) {
	res := run(t, "validate", "one.yaml", "two.yaml")

	if res.exitCode != 1 {
		t.Errorf("exit code = %d, want 1", res.exitCode)
	}
	if !strings.Contains(res.stderr, "usage:") {
		t.Errorf("stderr should be the usage text, got: %s", res.stderr)
	}
}
