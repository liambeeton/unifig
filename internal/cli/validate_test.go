func TestValidateReportsEveryProblemAtOnce(t *testing.T) {
	res := runValidate(t, `networks:
  - name: IoT
    subnet: nonsense
  - vlan: 5000
`, nil).mustFailWith(t, "networks[0].subnet", "networks[1]", "networks[1].vlan")

	// File order, so the list reads like the file the operator is looking at.
	subnet := strings.Index(res.stderr, "networks[0].subnet")
	vlan := strings.Index(res.stderr, "networks[1].vlan")
	if subnet > vlan {
		t.Errorf("problems should be listed in file order, got:\n%s", res.stderr)
	}
}

